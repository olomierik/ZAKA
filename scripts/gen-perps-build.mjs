// Writes ARCSENSE futures' compiled contracts from `forge build`'s output:
//   engine/src/perps/abi.ts    the ABIs (the site imports these)
//   engine/src/perps/build.ts  the creation code the engine deploys on Arc testnet, and the
//                              runtime code it checks deployed contracts against
//
//   forge build && node scripts/gen-perps-build.mjs           # regenerate
//   forge build && node scripts/gen-perps-build.mjs --check   # are they current?
//
// Regenerate whenever contracts/SensePerps.sol changes, with the Foundry version in .foundry-version.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const OUT = process.env.FORGE_OUT ?? 'contracts/out'
const ABI_FILE = 'engine/src/perps/abi.ts'
const BUILD_FILE = 'engine/src/perps/build.ts'
const check = process.argv.includes('--check')
const fail = msg => { console.error(`Error: ${msg}`); process.exit(1) }

function artifact(name) {
  const path = `${OUT}/SensePerps.sol/${name}.json`
  if (!existsSync(path)) fail(`${path} not found: run \`forge build\` in the ZAKA folder first.`)
  return JSON.parse(readFileSync(path, 'utf8'))
}
const perps = artifact('SensePerps')
const oracle = artifact('SenseOracle')
const usdc = artifact('SenseTestUSDC')

const { compiler, settings: s } = perps.metadata
if (s.evmVersion !== 'paris' || !s.viaIR || !s.optimizer?.enabled || s.optimizer.runs !== 200) {
  fail(`unexpected compiler settings ${JSON.stringify({ evmVersion: s.evmVersion, viaIR: s.viaIR, optimizer: s.optimizer })}: build with the repo's foundry.toml.`)
}
for (const a of [perps, oracle, usdc]) {
  if (Object.keys(a.bytecode.linkReferences ?? {}).length) fail('a contract links a library: this generator does not handle that.')
}
const size = a => (a.deployedBytecode.object.length - 2) / 2
if (size(perps) > 24_576) fail(`SensePerps is ${size(perps)} bytes, over the 24,576-byte limit.`)

const immutables = a => Object.values(a.deployedBytecode.immutableReferences ?? {}).flat()
  .map(r => [r.start, r.length]).sort((x, y) => x[0] - y[0])

const json = v => JSON.stringify(v)
const head = `// Generated by scripts/gen-perps-build.mjs from \`forge build\`: do not edit.
// contracts/SensePerps.sol, compiled with solc ${compiler.version}, via-IR, optimizer ${s.optimizer.runs} runs,
// EVM ${s.evmVersion} (foundry.toml). Still current? forge build && node scripts/gen-perps-build.mjs --check
`
const abiContent = `${head}
export const PERPS_ABI = ${json(perps.abi)} as const

export const ORACLE_ABI = ${json(oracle.abi)} as const

export const TEST_USDC_ABI = ${json(usdc.abi)} as const
`
const buildContent = `${head}
export const PERPS_COMPILER = ${json(compiler.version)}

/** Creation code. */
export const PERPS_BYTECODE = ${json(perps.bytecode.object)} as const
export const ORACLE_BYTECODE = ${json(oracle.bytecode.object)} as const
export const TEST_USDC_BYTECODE = ${json(usdc.bytecode.object)} as const

/** The code a deployment leaves on-chain, with zeros where the immutables go, and where they are. */
export const PERPS_RUNTIME = ${json(perps.deployedBytecode.object)} as const
export const PERPS_IMMUTABLES: readonly (readonly [number, number])[] = ${json(immutables(perps))}
export const ORACLE_RUNTIME = ${json(oracle.deployedBytecode.object)} as const
export const ORACLE_IMMUTABLES: readonly (readonly [number, number])[] = ${json(immutables(oracle))}
export const TEST_USDC_RUNTIME = ${json(usdc.deployedBytecode.object)} as const
export const TEST_USDC_IMMUTABLES: readonly (readonly [number, number])[] = ${json(immutables(usdc))}
`

if (check) {
  const noMeta = t => t.replace(/a264697066735822[0-9a-f]{68}64736f6c6343[0-9a-f]{6}0033/g, '')
  for (const [file, content] of [[ABI_FILE, abiContent], [BUILD_FILE, buildContent]]) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : ''
    if (current === content) { console.log(`${file} matches the build.`); continue }
    if (noMeta(current) === noMeta(content)) fail(`${file} differs from this build only in the metadata hash: build with the Foundry version in .foundry-version, regenerate and commit it.`)
    fail(`${file} is out of date: run \`forge build && node scripts/gen-perps-build.mjs\` and commit it.`)
  }
  process.exit(0)
}
writeFileSync(ABI_FILE, abiContent)
writeFileSync(BUILD_FILE, buildContent)
console.log(`wrote ${ABI_FILE} and ${BUILD_FILE} (SensePerps ${size(perps)} bytes, SenseOracle ${size(oracle)}, SenseTestUSDC ${size(usdc)})`)
