// Writes the prediction pool's compiled contracts from `forge build`'s output:
//   engine/src/predictpool/abi.ts    the ABIs (the site imports these)
//   engine/src/predictpool/build.ts  the creation code the engine deploys on Arc testnet, and the
//                                    runtime code it checks deployed contracts against
//
//   forge build && node scripts/gen-predict-pool-build.mjs           # regenerate
//   forge build && node scripts/gen-predict-pool-build.mjs --check   # are they current?
//
// Regenerate whenever contracts/ArcdexPredictPool.sol changes, with the Foundry version in .foundry-version.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const OUT = process.env.FORGE_OUT ?? 'contracts/out'
const ABI_FILE = 'engine/src/predictpool/abi.ts'
const BUILD_FILE = 'engine/src/predictpool/build.ts'
const check = process.argv.includes('--check')
const fail = msg => { console.error(`Error: ${msg}`); process.exit(1) }

function artifact(name) {
  const path = `${OUT}/ArcdexPredictPool.sol/${name}.json`
  if (!existsSync(path)) fail(`${path} not found: run \`forge build\` in the ZAKA folder first.`)
  return JSON.parse(readFileSync(path, 'utf8'))
}
const pool = artifact('ArcdexPredictPool')
const tok = artifact('ArcdexPredictToken')

const { compiler, settings: s } = pool.metadata
if (s.evmVersion !== 'paris' || !s.viaIR || !s.optimizer?.enabled || s.optimizer.runs !== 200) {
  fail(`unexpected compiler settings ${JSON.stringify({ evmVersion: s.evmVersion, viaIR: s.viaIR, optimizer: s.optimizer })}: build with the repo's foundry.toml.`)
}
for (const a of [pool, tok]) {
  if (Object.keys(a.bytecode.linkReferences ?? {}).length) fail('a contract links a library: this generator does not handle that.')
}
const size = a => (a.deployedBytecode.object.length - 2) / 2
if (size(pool) > 24_576) fail(`ArcdexPredictPool is ${size(pool)} bytes, over the 24,576-byte limit.`)

const immutables = a => Object.values(a.deployedBytecode.immutableReferences ?? {}).flat()
  .map(r => [r.start, r.length]).sort((x, y) => x[0] - y[0])

const json = v => JSON.stringify(v)
const head = `// Generated by scripts/gen-predict-pool-build.mjs from \`forge build\`: do not edit.
// contracts/ArcdexPredictPool.sol, compiled with solc ${compiler.version}, via-IR, optimizer ${s.optimizer.runs} runs,
// EVM ${s.evmVersion} (foundry.toml). Still current? forge build && node scripts/gen-predict-pool-build.mjs --check
`
const abiContent = `${head}
export const PREDICT_POOL_ABI = ${json(pool.abi)} as const

export const PREDICT_TOKEN_ABI = ${json(tok.abi)} as const
`
const buildContent = `${head}
export const PREDICT_POOL_COMPILER = ${json(compiler.version)}

/** Creation code (the pool deploys its token itself). */
export const PREDICT_POOL_BYTECODE = ${json(pool.bytecode.object)} as const

/** The code a deployment leaves on-chain, with zeros where the immutables go, and where they are. */
export const PREDICT_POOL_RUNTIME = ${json(pool.deployedBytecode.object)} as const
export const PREDICT_POOL_IMMUTABLES: readonly (readonly [number, number])[] = ${json(immutables(pool))}
export const PREDICT_TOKEN_RUNTIME = ${json(tok.deployedBytecode.object)} as const
export const PREDICT_TOKEN_IMMUTABLES: readonly (readonly [number, number])[] = ${json(immutables(tok))}
`

if (check) {
  const noMeta = t => t.replace(/a264697066735822[0-9a-f]{68}64736f6c6343[0-9a-f]{6}0033/g, '')
  for (const [file, content] of [[ABI_FILE, abiContent], [BUILD_FILE, buildContent]]) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : ''
    if (current === content) { console.log(`${file} matches the build.`); continue }
    if (noMeta(current) === noMeta(content)) fail(`${file} differs from this build only in the metadata hash: build with the Foundry version in .foundry-version, regenerate and commit it.`)
    fail(`${file} is out of date: run \`forge build && node scripts/gen-perps-build.mjs\` and commit it.`)
  }
  process.exit(0)
}
writeFileSync(ABI_FILE, abiContent)
writeFileSync(BUILD_FILE, buildContent)
console.log(`wrote ${ABI_FILE} and ${BUILD_FILE} (ArcdexPredictPool ${size(pool)} bytes, ArcdexPredictToken ${size(tok)})`)
