// Writes src/arcdex/lib/curveRouterBuild.ts: ArcDexCurveRouter's compiled
// code and ABI, and its simulation harness, from `forge build`'s output. The
// deploy page (/deploy/curve-router) deploys exactly this code from the
// owner's wallet, runs the harness against Arc's live curves first, and
// checks a deployed router's code against it afterwards.
//
//   forge build && node scripts/gen-curve-router-build.mjs           # regenerate
//   forge build && node scripts/gen-curve-router-build.mjs --check   # is it current?
//
// Regenerate whenever contracts/ArcDexCurveRouter.sol or the harness
// changes, with the Foundry version in .foundry-version.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const OUT = process.env.FORGE_OUT ?? 'contracts/out' // where forge build wrote its artifacts
const TARGET = 'src/arcdex/lib/curveRouterBuild.ts'
const check = process.argv.includes('--check')
const fail = msg => { console.error(`Error: ${msg}`); process.exit(1) }

function artifact(file, name) {
  const path = `${OUT}/${file}/${name}.json`
  if (!existsSync(path)) fail(`${path} not found: run \`forge build\` in the ZAKA folder first.`)
  return JSON.parse(readFileSync(path, 'utf8'))
}
const router = artifact('ArcDexCurveRouter.sol', 'ArcDexCurveRouter')
const harness = artifact('ArcDexCurveRouterSimHarness.sol', 'ArcDexCurveRouterSimHarness')

const { compiler, settings } = router.metadata
const s = settings
if (s.evmVersion !== 'paris' || !s.viaIR || !s.optimizer?.enabled || s.optimizer.runs !== 200) {
  fail(`unexpected compiler settings ${JSON.stringify({ evmVersion: s.evmVersion, viaIR: s.viaIR, optimizer: s.optimizer })}: build with the repo's foundry.toml.`)
}
if (Object.keys(router.bytecode.linkReferences ?? {}).length) fail('the router links a library: this generator does not handle that.')

// Positions of the immutables (factories, USDC) in the runtime code: the
// artifact has zeros there, a deployed router its constructor arguments.
const immutables = Object.values(router.deployedBytecode.immutableReferences ?? {}).flat()
  .map(r => [r.start, r.length]).sort((a, b) => a[0] - b[0])

const json = v => JSON.stringify(v)
const content = `// Generated by scripts/gen-curve-router-build.mjs from \`forge build\`: do not edit.
// ArcDexCurveRouter (contracts/ArcDexCurveRouter.sol) and its simulation
// harness (contracts/test/sim/ArcDexCurveRouterSimHarness.sol), compiled with
// solc ${compiler.version}, via-IR, optimizer ${s.optimizer.runs} runs, EVM ${s.evmVersion} (foundry.toml).
// Still current? forge build && node scripts/gen-curve-router-build.mjs --check

export const ROUTER_COMPILER = ${json(compiler.version)}

export const ROUTER_ABI = ${json(router.abi)} as const

/** Creation code: deploy it with the five constructor arguments. */
export const ROUTER_BYTECODE = ${json(router.bytecode.object)} as const

/** The code a deployment leaves on-chain, with zeros where the immutables go. */
export const ROUTER_RUNTIME = ${json(router.deployedBytecode.object)} as const

/** [byte offset, length] of each immutable in ROUTER_RUNTIME. */
export const ROUTER_IMMUTABLES: readonly (readonly [number, number])[] = ${json(immutables)}

export const HARNESS_ABI = ${json(harness.abi)} as const

/** The harness's runtime code, injected at a scratch address with a state override. */
export const HARNESS_RUNTIME = ${json(harness.deployedBytecode.object)} as const
`

if (check) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
  if (current === content) { console.log(`${TARGET} matches the build.`); process.exit(0) }
  // Solidity appends a hash of the sources and compiler settings to the code
  // (the metadata). Only that differing means the same code: a comment
  // changed, or another Foundry version passed other settings.
  const noMeta = t => t.replace(/a264697066735822[0-9a-f]{68}64736f6c6343[0-9a-f]{6}0033/g, '')
  if (noMeta(current) === noMeta(content)) fail(`${TARGET} differs from this build only in the metadata hash (a comment changed in the source, or another Foundry version built it): build with the Foundry version in .foundry-version, regenerate and commit it.`)
  fail(`${TARGET} is out of date: run \`forge build && node scripts/gen-curve-router-build.mjs\` and commit it.`)
}
writeFileSync(TARGET, content)
console.log(`wrote ${TARGET} (router ${(router.bytecode.object.length - 2) / 2} bytes, harness ${(harness.deployedBytecode.object.length - 2) / 2} bytes)`)
