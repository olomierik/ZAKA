const TRANSLATIONS: Record<Lang, Translations> = { en: EN, zh: ZH, fr: FR, de: DE, ar: AR }

interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: Translations
  isRTL: boolean
}

const I18nContext = createContext<I18nCtx>({
  lang: 'en', setLang: () => {}, t: EN, isRTL: false,
})

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { return (localStorage.getItem('zaka_lang') as Lang) ?? 'en' } catch { return 'en' }
  })

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('zaka_lang', l) } catch {}
    document.documentElement.setAttribute('lang', l)
    document.documentElement.setAttribute('dir', RTL_LANGS.includes(l) ? 'rtl' : 'ltr')
  }, [])

  useEffect(() => {
    document.documentElement.setAttribute('lang', lang)
    document.documentElement.setAttribute('dir', RTL_LANGS.includes(lang) ? 'rtl' : 'ltr')
  }, [lang])

  const isRTL = RTL_LANGS.includes(lang)
  const t = TRANSLATIONS[lang]

  return <I18nContext.Provider value={{ lang, setLang, t, isRTL }}>{children}</I18nContext.Provider>
}

export function useI18n() { return useContext(I18nContext) }
